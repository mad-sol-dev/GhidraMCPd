#!/usr/bin/env python3
"""Write the plugin HTTP reference (docs/reference/plugin-api.md) from the Java source.

The routes are read from the plugin's register*Handler calls, and whether the
bridge calls a route from its whitelist, so the list cannot drift from the
code.  The convention text above the list is kept here.  A unit test
regenerates the page and fails when it drifts.

Usage::

    python scripts/gen_plugin_routes_md.py > docs/reference/plugin-api.md
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import List, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

PLUGIN = ROOT / "src" / "main" / "java" / "com" / "lauriewired" / "GhidraMCPPlugin.java"

_REGISTRATION = re.compile(r'register(Program|Project|Write)Handler\(server, "(/[^"]+)"')
_LEVEL = re.compile(r"static final int API_LEVEL = (\d+);")

KINDS = (
    ("Program", "Read routes", "Need an open program; 425 `NOT_READY` without one."),
    ("Project", "Project routes", "Answer without an open program."),
    ("Write", "Write routes",
     "Change the program or its file. With `domain_file_id` set and naming another "
     "program, refused with 409 before anything is written."),
)

HEADER = """# Plugin HTTP API

Generated by `scripts/gen_plugin_routes_md.py` from the plugin source; do not edit by hand.

The plugin embeds an HTTP server in Ghidra (default `127.0.0.1:8080`; *Edit > Tool
Options > GhidraMCP HTTP Server* sets port and bind address). It has no
authentication. The write guard (`GHIDRA_MCP_ENABLE_WRITES`) lives in the bridge, not
here: binding to anything but loopback exposes the write routes to everyone who can
reach the port.

## Answer convention (API {level})

- Every response carries `X-GhidraMCP-API: {level}`. `GET /plugin_version` reports
  `{{"version": ..., "api": {level}}}` and works without an open program.
- Every failure is an HTTP 4xx/5xx with one JSON body,
  `{{"status": "error", "code": ..., "error": ...}}`:

  | Status | Code | Meaning |
  |---|---|---|
  | 400 | `INVALID_REQUEST` | a missing or malformed parameter, a non-integer number, an out-of-range `length`/`count`, a cursor this route did not issue |
  | 404 | `NOT_FOUND` | what was asked about is not there (no function at the address) |
  | 404 | `UNMAPPED` | no memory at the address |
  | 409 | `CONFLICT` | the request contradicts the program (name exists, write to another program) |
  | 425 | `NOT_READY` | no program open, or no tool to answer |
  | 500 | `INTERNAL` | Ghidra failed; the message says how |

- A route the plugin does not have is the JDK server's own HTML 404, not JSON.
- Flags are JSON booleans. A scalar search stopped by its inspection cap says
  `"truncated": true` with a `"reason"`; there is no cursor to resume it.
- The bridge accepts exactly this level and refuses any other (`PLUGIN_TOO_OLD`,
  `PLUGIN_TOO_NEW`), because the same answer means something else at another level.

## Routes

{count} routes plus `/plugin_version`. "Bridge" marks the routes the bridge calls
(`bridge/ghidra/whitelist.py`); the others are there for scripts and older clients.
"""


def routes() -> List[Tuple[str, str]]:
    return _REGISTRATION.findall(PLUGIN.read_text(encoding="utf-8"))


def api_level() -> int:
    match = _LEVEL.search(PLUGIN.read_text(encoding="utf-8"))
    if match is None:
        raise SystemExit("API_LEVEL not found in the plugin source")
    return int(match.group(1))


def bridge_routes() -> Set[str]:
    from bridge.ghidra.whitelist import DEFAULT_WHITELIST

    return {"/" + alias for entries in DEFAULT_WHITELIST.values() for entry in entries for alias in entry.aliases}


def render() -> str:
    found = routes()
    used = bridge_routes()
    out = [HEADER.format(level=api_level(), count=len(found)).rstrip()]
    for kind, title, note in KINDS:
        paths = sorted(path for k, path in found if k == kind)
        out += ["", f"### {title}", "", note, "", "| Route | Bridge |", "|---|---|"]
        out += [f"| `{path}` | {'yes' if path in used else ''} |" for path in paths]
    return "\n".join(out) + "\n"


def main() -> int:
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":  # pragma: no cover - script entry point
    raise SystemExit(main())
